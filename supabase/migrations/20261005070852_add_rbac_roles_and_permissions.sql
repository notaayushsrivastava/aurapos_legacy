
-- AuraPOS RBAC schema
CREATE TABLE IF NOT EXISTS public.permissions (
  key text PRIMARY KEY,
  module text NOT NULL,
  name text NOT NULL,
  description text NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS public.roles (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id bigint NOT NULL REFERENCES public.salons(id) ON DELETE CASCADE,
  role_name text NOT NULL,
  description text NOT NULL DEFAULT '',
  is_system_locked integer NOT NULL DEFAULT 0,
  created_at bigint NOT NULL DEFAULT (EXTRACT(epoch FROM now()))::bigint,
  updated_at bigint NOT NULL DEFAULT (EXTRACT(epoch FROM now()))::bigint
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_roles_tenant_name_ci
  ON public.roles (tenant_id, lower(role_name));

CREATE INDEX IF NOT EXISTS idx_roles_tenant_id
  ON public.roles (tenant_id);

CREATE TABLE IF NOT EXISTS public.role_permissions (
  role_id bigint NOT NULL REFERENCES public.roles(id) ON DELETE CASCADE,
  permission_key text NOT NULL REFERENCES public.permissions(key) ON DELETE CASCADE,
  PRIMARY KEY (role_id, permission_key)
);

ALTER TABLE public.accounts
  ADD COLUMN IF NOT EXISTS role_id bigint REFERENCES public.roles(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_accounts_role_id
  ON public.accounts(role_id);

ALTER TABLE public.salon_settings
  ADD COLUMN IF NOT EXISTS default_role_id bigint REFERENCES public.roles(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_salon_settings_default_role
  ON public.salon_settings(default_role_id);

ALTER TABLE public.permissions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.roles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.role_permissions ENABLE ROW LEVEL SECURITY;

