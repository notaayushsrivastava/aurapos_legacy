    "amount" integer NOT NULL,
    "payment_mode" text DEFAULT 'Cash'::text NOT NULL,
    "received_by" text DEFAULT ''::text,
    "notes" text DEFAULT ''::text,
    "created_at" bigint DEFAULT (EXTRACT(epoch FROM now()))::bigint NOT NULL
);

