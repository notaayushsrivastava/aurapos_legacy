-- Compatible with PostgreSQL / Supabase and idempotent.

-- 1. Create products table for retail inventory
CREATE TABLE IF NOT EXISTS "public"."products" (
    "id" bigint NOT NULL,
    "account_id" bigint NOT NULL,
    "name" text NOT NULL,
    "category" text DEFAULT 'Retail'::text NOT NULL,
    "sku" text DEFAULT ''::text,
    "barcode" text DEFAULT ''::text,
    "price" integer DEFAULT 0 NOT NULL,
    "cost_price" integer DEFAULT 0,
    "stock" integer DEFAULT 0 NOT NULL,
    "tax_rate" double precision DEFAULT 18.0 NOT NULL,
    "description" text DEFAULT ''::text,
    "active" integer DEFAULT 1 NOT NULL,
    "created_at" bigint DEFAULT (EXTRACT(epoch FROM now()))::bigint NOT NULL
);

ALTER TABLE IF EXISTS "public"."products" OWNER TO "postgres";

ALTER TABLE IF EXISTS "public"."products" 
ALTER COLUMN "id" ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME "public"."products_id_seq"
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'products_pkey'
    ) THEN
        ALTER TABLE "public"."products" ADD CONSTRAINT "products_pkey" PRIMARY KEY ("id");
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS "idx_products_account_id" ON "public"."products" ("account_id");
CREATE INDEX IF NOT EXISTS "idx_products_category" ON "public"."products" ("category");

