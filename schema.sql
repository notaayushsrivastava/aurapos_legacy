-- =========================================================
-- AuraPOS Supabase / PostgreSQL Schema Definition
-- =========================================================

CREATE TABLE IF NOT EXISTS public.salons (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  phone text NOT NULL UNIQUE,
  salon_name text NOT NULL,
  email text NOT NULL UNIQUE,
  created_on bigint NOT NULL DEFAULT (EXTRACT(epoch FROM now()))::bigint,
  plan text NOT NULL DEFAULT 'free'::text,
  expires_on bigint,
  logo text,
  billing_cycle text NOT NULL DEFAULT 'monthly'::text,
  address text NOT NULL DEFAULT ''::text,
  opening_hours text NOT NULL DEFAULT '{}'::text,
  latitude double precision,
  longitude double precision,
  auth_uid uuid
);

CREATE TABLE IF NOT EXISTS public.accounts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  auth_id bigint NOT NULL,
  username text NOT NULL UNIQUE,
  password text NOT NULL,
  auth_level text NOT NULL DEFAULT 'admin'::text,
  supabase_uid uuid,
  CONSTRAINT accounts_auth_id_fkey FOREIGN KEY (auth_id) REFERENCES public.salons(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public.pendingorders (
  id text PRIMARY KEY,
  amount bigint NOT NULL,
  created_at bigint NOT NULL,
  plan text,
  receipt text,
  email text,
  phone text,
  salon_id bigint
);

CREATE TABLE IF NOT EXISTS public.subscriptions (
  id text PRIMARY KEY,
  amount bigint NOT NULL,
  plan text,
  billing_cycle text NOT NULL DEFAULT 'monthly'::text,
  receipt text,
  email text,
  phone text,
  created_at bigint,
  salon_id bigint
);

CREATE TABLE IF NOT EXISTS public.deletion_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  salon_id bigint NOT NULL,
  email text,
  reason text,
  requested_at bigint NOT NULL DEFAULT (EXTRACT(epoch FROM now()))::bigint,
  status text NOT NULL DEFAULT 'pending'::text,
  CONSTRAINT deletion_requests_salon_id_fkey FOREIGN KEY (salon_id) REFERENCES public.salons(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public.categories (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id bigint NOT NULL,
  name text NOT NULL,
  created_at bigint NOT NULL DEFAULT (EXTRACT(epoch FROM now()))::bigint,
  CONSTRAINT categories_account_id_fkey FOREIGN KEY (account_id) REFERENCES public.salons(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public.services (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id bigint NOT NULL,
  name text NOT NULL,
  category text NOT NULL DEFAULT 'Uncategorised'::text,
  duration integer NOT NULL DEFAULT 30,
  price integer NOT NULL DEFAULT 0,
  description text NOT NULL DEFAULT ''::text,
  gender text NOT NULL DEFAULT 'Any'::text,
  staff text NOT NULL DEFAULT 'Any Stylist'::text,
  active integer NOT NULL DEFAULT 1,
  created_at bigint NOT NULL DEFAULT (EXTRACT(epoch FROM now()))::bigint,
  CONSTRAINT services_account_id_fkey FOREIGN KEY (account_id) REFERENCES public.salons(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public.staff (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id bigint NOT NULL,
  name text NOT NULL,
  role text NOT NULL DEFAULT 'Stylist'::text,
  phone text,
  gender text,
  email text,
  total_revenue bigint NOT NULL DEFAULT 0,
  services_done bigint NOT NULL DEFAULT 0,
  created_on bigint NOT NULL DEFAULT (EXTRACT(epoch FROM now()))::bigint,
  CONSTRAINT staff_account_id_fkey FOREIGN KEY (account_id) REFERENCES public.salons(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public.appointments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id bigint NOT NULL,
  client text NOT NULL,
  phone text NOT NULL,
  email text NOT NULL DEFAULT ''::text,
  service text NOT NULL,
  time text NOT NULL,
  date text NOT NULL,
  staff text NOT NULL,
  price integer NOT NULL DEFAULT 0,
  duration integer NOT NULL DEFAULT 30,
  status text NOT NULL DEFAULT 'Confirmed'::text,
  notes text NOT NULL DEFAULT ''::text,
  CONSTRAINT appointments_account_id_fkey FOREIGN KEY (account_id) REFERENCES public.salons(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public.bills (
  id text PRIMARY KEY,
  account_id bigint NOT NULL,
  client_name text NOT NULL DEFAULT ''::text,
  client_phone text NOT NULL DEFAULT ''::text,
  subtotal integer NOT NULL DEFAULT 0,
  discount integer NOT NULL DEFAULT 0,
  tax integer NOT NULL DEFAULT 0,
  grand_total integer NOT NULL DEFAULT 0,
  payment_mode text NOT NULL DEFAULT 'Cash'::text,
  created_at bigint NOT NULL,
  items_json text NOT NULL DEFAULT '[]'::text,
  CONSTRAINT bills_account_id_fkey FOREIGN KEY (account_id) REFERENCES public.salons(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public.customers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id bigint NOT NULL,
  name text NOT NULL,
  phone text,
  email text,
  notes text,
  created_at bigint NOT NULL DEFAULT (EXTRACT(epoch FROM now()))::bigint,
  CONSTRAINT customers_account_id_fkey FOREIGN KEY (account_id) REFERENCES public.salons(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public.app_settings (
  key text PRIMARY KEY,
  value text,
  updated_at bigint NOT NULL DEFAULT (EXTRACT(epoch FROM now()))::bigint
);

CREATE TABLE IF NOT EXISTS public.salon_settings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  salon_id bigint UNIQUE,
  payment_methods jsonb DEFAULT '{}'::jsonb,
  created_at bigint,
  updated_at bigint,
  CONSTRAINT salon_settings_salon_id_fkey FOREIGN KEY (salon_id) REFERENCES public.salons(id) ON DELETE CASCADE
);

-- =========================================================
-- Performance Indexes for High-Concurrency Queries
-- =========================================================
CREATE INDEX IF NOT EXISTS idx_accounts_auth_id ON public.accounts(auth_id);
CREATE INDEX IF NOT EXISTS idx_accounts_username ON public.accounts(username);
CREATE INDEX IF NOT EXISTS idx_bills_account_created ON public.bills(account_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_bills_payment_mode ON public.bills(payment_mode);
CREATE INDEX IF NOT EXISTS idx_appointments_account_date ON public.appointments(account_id, date);
CREATE INDEX IF NOT EXISTS idx_services_account_active ON public.services(account_id, active);
CREATE INDEX IF NOT EXISTS idx_staff_account_id ON public.staff(account_id);
CREATE INDEX IF NOT EXISTS idx_customers_account_phone ON public.customers(account_id, phone);
CREATE INDEX IF NOT EXISTS idx_categories_account_id ON public.categories(account_id);
CREATE INDEX IF NOT EXISTS idx_subscriptions_salon_id ON public.subscriptions(salon_id);
CREATE INDEX IF NOT EXISTS idx_pendingorders_salon_id ON public.pendingorders(salon_id);
CREATE INDEX IF NOT EXISTS idx_deletion_requests_salon ON public.deletion_requests(salon_id, status);

-- =========================================================
-- Disable RLS on server-only tables or grant full access
-- =========================================================
ALTER TABLE public.app_settings DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.salon_settings DISABLE ROW LEVEL SECURITY;
